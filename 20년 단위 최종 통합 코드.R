진단_함수 <- function(형식명) {
  
  y <- 전체_20년_자료[[형식명]]
  
  평균 <- mean(y)
  분산 <- var(y)
  
  data.frame(
    형식 = 형식명,
    N = length(y),
    총용례수 = sum(y),
    영구간수 = sum(y == 0),
    영비율 = mean(y == 0),
    평균 = 평균,
    분산 = 분산,
    
    분산평균비 =
      ifelse(
        평균 > 0,
        분산 / 평균,
        NA
      ),
    
    최소값 = min(y),
    최대값 = max(y)
  )
}


