# ============================================================
# 12. 전체 23구간의 순수 시간추세
# ============================================================

전체시간_분석함수 <- function(형식명) {
  
  분석용 <- 전체_20년_자료 %>%
    transmute(
      용례수 = .data[[형식명]],
      시간20_c
    )
  
  fit <- glm(
    용례수 ~ 시간20_c,
    family = quasipoisson(link = "log"),
    data = 분석용
  )
  
  sm <- coef(summary(fit))
  
  b <- sm["시간20_c", "Estimate"]
  se <- sm["시간20_c", "Std. Error"]
  p <- sm["시간20_c", ncol(sm)]
  
  df <- df.residual(fit)
  crit <- qt(0.975, df)
  
  data.frame(
    형식 = 형식명,
    N = nrow(분석용),
    시간계수 = b,
    IRR_20년 = exp(b),
    CI하한 = exp(b - crit * se),
    CI상한 = exp(b + crit * se),
    p값 = p,
    dispersion = summary(fit)$dispersion
  )
}


전체시간_결과 <- do.call(
  rbind,
  lapply(
    분석_형식,
    전체시간_분석함수
  )
)


