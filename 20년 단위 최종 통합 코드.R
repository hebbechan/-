# ============================================================
# 14. offset(beta=1) 가정 검정
#
# offset(log(감히))는
# log(감히)의 계수를 정확히 1로 고정하는 것과 같다.
#
# 따라서 자유롭게 추정한 beta가 1과 다른지 검정한다.
# ============================================================

offset_검정_함수 <- function(형식명) {
  
  분석용 <- 감히_분석자료 %>%
    transmute(
      용례수 = .data[[형식명]],
      시간20_c,
      log_감히
    )
  
  fit <- glm(
    용례수 ~ 시간20_c + log_감히,
    family = quasipoisson(link = "log"),
    data = 분석용
  )
  
  sm <- coef(summary(fit))
  
  beta <- sm["log_감히", "Estimate"]
  se <- sm["log_감히", "Std. Error"]
  
  df <- df.residual(fit)
  
  t_beta1 <- (beta - 1) / se
  
  p_beta1 <- 2 * pt(
    abs(t_beta1),
    df = df,
    lower.tail = FALSE
  )
  
  crit <- qt(0.975, df)
  
  data.frame(
    형식 = 형식명,
    감히계수 = beta,
    표준오차 = se,
    CI하한 = beta - crit * se,
    CI상한 = beta + crit * se,
    beta1_t = t_beta1,
    beta1_p값 = p_beta1,
    
    판정 =
      ifelse(
        p_beta1 < 0.05,
        "β=1 가정 기각",
        "β=1 가정 기각 못함"
      )
  )
}


offset_가정검정 <- do.call(
  rbind,
  lapply(
    분석_형식,
    offset_검정_함수
  )
)


offset_가정검정표 <- offset_가정검정 %>%
  mutate(
    across(
