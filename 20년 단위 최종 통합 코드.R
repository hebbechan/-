# 26. 개별 결과표 정리 함수
# ============================================================

상대점유율_결과정리 <- function(분석객체) {
  
  분석객체$result %>%
    mutate(
      across(
        c(
          시간계수,
          OR_20년,
          CI하한,
          CI상한,
          binomial_dispersion,
          quasi_dispersion
        ),
        ~ round(.x, 3)
      ),
      
      p값 = signif(
        p값,
        4
      ),
      
      방향 = case_when(
        
        시간계수 < 0 &
          p값 < 0.05 ~
          "유의한 감소",
        
        시간계수 > 0 &
          p값 < 0.05 ~
          "유의한 증가",
        
        시간계수 < 0 ~
          "감소 방향이나 비유의",
        
        시간계수 > 0 ~
          "증가 방향이나 비유의",
        
        TRUE ~
          "변화 없음"
      )
    )
}


