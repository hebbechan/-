        감히계수,
        감히_SE,
        감히_CI하한,
        감히_CI상한,
        dispersion
      ),
      ~ round(.x, 3)
    ),
    
    시간_p값 =
      signif(시간_p값, 4),
    
    감히_p값 =
      signif(감히_p값, 4)
  )


