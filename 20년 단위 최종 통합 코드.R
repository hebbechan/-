감히추가_함수 <- function(형식명) {
  
  obj <- 주분석_모형목록[[형식명]]
  
  비교 <- anova(
    obj$m0,
    obj$m1,
    test = "F"
  )
  
  data.frame(
    형식 = 형식명,
    Deviance = 비교$Deviance[2],
    F = 비교$F[2],
    p값 = 비교$`Pr(>F)`[2]
  )
}


감히추가_결과 <- do.call(
  rbind,
  lapply(
    분석_형식,
    감히추가_함수
  )
)


