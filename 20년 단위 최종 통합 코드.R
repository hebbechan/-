# ============================================================
# 19. 안전한 NB 함수
# ============================================================

safe_nb <- function(formula, data) {
  
  tryCatch(
    suppressWarnings(
      MASS::glm.nb(
        formula,
        data = data,
        control = glm.control(maxit = 100)
      )
    ),
    
    error = function(e) {
      NULL
    }
  )
}


