# 20. NB 민감도 분석
# ============================================================

NB_민감도_함수 <- function(형식명) {
  
  분석용 <- 감히_분석자료 %>%
    transmute(
      용례수 = .data[[형식명]],
      시간20_c,
      log_감히
    )
  
  fit <- safe_nb(
    용례수 ~ 시간20_c + log_감히,
    data = 분석용
  )
  
  if (is.null(fit)) {
    
    return(
      data.frame(
        형식 = 형식명,
        NB성공 = FALSE,
        theta = NA,
        시간계수 = NA,
        시간_IRR = NA,
        시간_p값 = NA,
        감히계수 = NA,
        감히_p값 = NA
      )
    )
  }
  
  sm <- coef(summary(fit))
  theta <- fit$theta
  
  정상여부 <-
    is.finite(theta) &&
    theta > 0 &&
    theta < 1e6
  
  data.frame(
    형식 = 형식명,
    NB성공 = 정상여부,
    theta = theta,
    
    시간계수 =
      sm["시간20_c", "Estimate"],
    
    시간_IRR =
      exp(sm["시간20_c", "Estimate"]),
    
    시간_p값 =
      sm["시간20_c", ncol(sm)],
    
    감히계수 =
      sm["log_감히", "Estimate"],
    
    감히_p값 =
      sm["log_감히", ncol(sm)]
  )
}


NB_민감도 <- do.call(
  rbind,
  lapply(
    분석_형식,
    NB_민감도_함수
  )
)


