# ============================================================
# 21. 상대점유율 공통 함수
#
# 여기서는 감히=0도 유지한다.
#
# 단, 성공+실패=0이면 비율 자체가 정의되지 않으므로
# 해당 구간만 제외한다.
# ============================================================

상대점유율_분석 <- function(
    성공변수,
    실패변수,
    분석명
) {
  
  분석용 <- 전체_20년_자료 %>%
    transmute(
      이십년대,
      시간20_c,
      
      성공 =
        .data[[성공변수]],
      
      실패 =
        .data[[실패변수]]
    ) %>%
    mutate(
      합계 = 성공 + 실패
    ) %>%
    filter(
      합계 > 0
    )
  
  # 일반 binomial:
  # 과산포 확인용
  m_binom <- glm(
    cbind(성공, 실패) ~ 시간20_c,
    family = binomial(link = "logit"),
    data = 분석용
  )
  
  binom_dispersion <-
    sum(
      residuals(
        m_binom,
        type = "pearson"
      )^2
    ) /
    df.residual(m_binom)
  
  # 최종 quasi-binomial
  m_quasi <- glm(
    cbind(성공, 실패) ~ 시간20_c,
    family = quasibinomial(link = "logit"),
    data = 분석용
  )
  
  sm <- coef(summary(m_quasi))
  
  b <- sm["시간20_c", "Estimate"]
  se <- sm["시간20_c", "Std. Error"]
  p <- sm["시간20_c", ncol(sm)]
  
  df <- df.residual(m_quasi)
  crit <- qt(0.975, df)
  
  결과 <- data.frame(
    분석 = 분석명,
    N구간 = nrow(분석용),
    성공변수 = 성공변수,
    비교변수 = 실패변수,
    
    시간계수 = b,
    OR_20년 = exp(b),
    
    CI하한 =
      exp(b - crit * se),
    
    CI상한 =
      exp(b + crit * se),
    
    p값 = p,
    
    binomial_dispersion =
      binom_dispersion,
    
    quasi_dispersion =
      summary(m_quasi)$dispersion
  )
  
  list(
    data = 분석용,
    binomial_model = m_binom,
    quasi_model = m_quasi,
    result = 결과
  )
}


