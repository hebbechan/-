# ============================================================
# 15. 감히 공변량 주분석
#
# M0 = Y ~ 시간
# M1 = Y ~ 시간 + log(감히)
#
# 중요:
# M0와 M1은 반드시 같은 관측치를 사용해야 하므로
# 둘 다 감히>0 자료를 사용한다.
# ============================================================

주분석_함수 <- function(형식명) {
  
  분석용 <- 감히_분석자료 %>%
    transmute(
      이십년대,
      용례수 = .data[[형식명]],
      시간20_c,
      감히,
      log_감히
    )
  
  m0 <- glm(
    용례수 ~ 시간20_c,
    family = quasipoisson(link = "log"),
    data = 분석용
  )
  
  m1 <- glm(
    용례수 ~ 시간20_c + log_감히,
    family = quasipoisson(link = "log"),
    data = 분석용
  )
  
  list(
    형식 = 형식명,
    data = 분석용,
    m0 = m0,
    m1 = m1
  )
}


주분석_모형목록 <- setNames(
  lapply(
    분석_형식,
    주분석_함수
  ),
  분석_형식
)


# ============================================================
# 16. 주모형 결과 추출
#
# 문법 수정:
# 주분석_모형목록[[형식명]]
# ============================================================

주모형_결과함수 <- function(형식명) {
  
  obj <- 주분석_모형목록[[형식명]]
  
  fit <- obj$m1
  sm <- coef(summary(fit))
  
  df <- df.residual(fit)
  crit <- qt(0.975, df)
  
  b_time <- sm["시간20_c", "Estimate"]
  se_time <- sm["시간20_c", "Std. Error"]
  p_time <- sm["시간20_c", ncol(sm)]
  
  b_gamhi <- sm["log_감히", "Estimate"]
  se_gamhi <- sm["log_감히", "Std. Error"]
  p_gamhi <- sm["log_감히", ncol(sm)]
  
  data.frame(
    형식 = 형식명,
    N = nrow(obj$data),
    
    시간계수 = b_time,
    시간_SE = se_time,
    시간_IRR = exp(b_time),
    
    시간_CI하한 =
      exp(b_time - crit * se_time),
    
    시간_CI상한 =
      exp(b_time + crit * se_time),
    
    시간_p값 = p_time,
    
    감히계수 = b_gamhi,
    감히_SE = se_gamhi,
    
    감히_CI하한 =
      b_gamhi - crit * se_gamhi,
    
    감히_CI상한 =
      b_gamhi + crit * se_gamhi,
    
    감히_p값 = p_gamhi,
    
    dispersion =
      summary(fit)$dispersion
  )
}


주모형_결과 <- do.call(
  rbind,
  lapply(
    분석_형식,
    주모형_결과함수
  )
)


주모형_결과표 <- 주모형_결과 %>%
  mutate(
    across(
      c(
        시간계수,
